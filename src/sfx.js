// ---------- little synth toolkit ----------
function sfxNoise(ctx, dur, color = 'white') {
  const n = Math.max(1, Math.round(dur * ctx.sampleRate)), b = ctx.createBuffer(1, n, ctx.sampleRate), d = b.getChannelData(0);
  let last = 0, b0 = 0, b1 = 0, b2 = 0;
  for (let i = 0; i < n; i++) {
    const w = Math.random() * 2 - 1;
    if (color === 'brown') { last = (last + 0.02 * w) / 1.02; d[i] = last * 3.5; }
    else if (color === 'pink') { b0 = 0.99765 * b0 + w * 0.099; b1 = 0.963 * b1 + w * 0.2965; b2 = 0.57 * b2 + w * 1.0527; d[i] = (b0 + b1 + b2 + w * 0.1848) * 0.2; }
    else d[i] = w;
  }
  const s = ctx.createBufferSource(); s.buffer = b; return s;
}
// gain envelope: points [[t, v], ...] (t in seconds from `at`)
function sfxEnv(ctx, at, pts, exp) {
  const g = ctx.createGain(); g.gain.setValueAtTime(pts[0][1], at + pts[0][0]);
  for (let i = 1; i < pts.length; i++) {
    const [t, v] = pts[i];
    if (exp && v > 0 && pts[i - 1][1] > 0) g.gain.exponentialRampToValueAtTime(v, at + t); else g.gain.linearRampToValueAtTime(v, at + t);
  }
  return g;
}
function sfxOsc(ctx, type, at, freqPts, ampPts, out, opts = {}) {
  const o = ctx.createOscillator(); o.type = type;
  o.frequency.setValueAtTime(freqPts[0][1], at + freqPts[0][0]);
  for (let i = 1; i < freqPts.length; i++) o.frequency[opts.linear ? 'linearRampToValueAtTime' : 'exponentialRampToValueAtTime'](Math.max(1, freqPts[i][1]), at + freqPts[i][0]);
  if (opts.detune) o.detune.value = opts.detune;
  const g = sfxEnv(ctx, at, ampPts);
  o.connect(g); g.connect(out);
  o.start(at); o.stop(at + ampPts[ampPts.length - 1][0] + 0.02);
  return o;
}
function sfxFilter(ctx, type, f, q = 1) { const b = ctx.createBiquadFilter(); b.type = type; b.frequency.value = f; b.Q.value = q; return b; }
function sfxReverb(ctx, out, seconds = 1.6, wet = 0.35) {
  const n = Math.round(seconds * ctx.sampleRate), b = ctx.createBuffer(2, n, ctx.sampleRate);
  for (let c = 0; c < 2; c++) { const d = b.getChannelData(c); for (let i = 0; i < n; i++) d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / n, 3); }
  const cv = ctx.createConvolver(); cv.buffer = b;
  const w = ctx.createGain(); w.gain.value = wet; const dry = ctx.createGain(); dry.gain.value = 1;
  const inp = ctx.createGain(); inp.connect(dry); inp.connect(cv); cv.connect(w); dry.connect(out); w.connect(out);
  return inp;
}
// noise through a sweeping band-pass = whoosh
function sfxWhoosh(ctx, out, at, dur, f0, f1, peak = 0.5, q = 1.2, color = 'pink') {
  const n = sfxNoise(ctx, dur, color), bp = sfxFilter(ctx, 'bandpass', f0, q);
  bp.frequency.setValueAtTime(f0, at); bp.frequency.exponentialRampToValueAtTime(f1, at + dur);
  const g = sfxEnv(ctx, at, [[0, 0.0001], [dur * peak, 1], [dur, 0.0001]], true);
  n.connect(bp); bp.connect(g); g.connect(out); n.start(at); n.stop(at + dur);
}
function sfxKick(ctx, out, at, f0 = 150, f1 = 40, len = 0.5, vol = 1) {
  sfxOsc(ctx, 'sine', at, [[0, f0], [len * 0.6, f1]], [[0, vol], [len, 0.0001]], out);
}
function sfxClickNoise(ctx, out, at, len = 0.02, f = 3000, vol = 0.6) {
  const n = sfxNoise(ctx, len), hp = sfxFilter(ctx, 'bandpass', f, 1.5), g = sfxEnv(ctx, at, [[0, vol], [len, 0.0001]], true);
  n.connect(hp); hp.connect(g); g.connect(out); n.start(at); n.stop(at + len);
}

