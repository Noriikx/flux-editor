// ---------- rendering ----------
const sfxCache = new Map(); // id -> { blob, url }
async function sfxRender(s) {
  if (sfxCache.has(s.id)) return sfxCache.get(s.id);
  const len = s.len + 0.15;
  const ctx = new OfflineAudioContext(2, Math.ceil(len * SFX_SR), SFX_SR);
  const master = ctx.createGain(); master.gain.value = 0.9;
  const comp = ctx.createDynamicsCompressor(); comp.threshold.value = -6; comp.ratio.value = 4;
  master.connect(comp); comp.connect(ctx.destination);
  s.make(ctx, master);
  const buf = await ctx.startRendering();
  // normalize to -1 dBFS so every sound has a similar loudness
  let peak = 0;
  for (let ch = 0; ch < 2; ch++) { const d = buf.getChannelData(ch); for (let i = 0; i < d.length; i++) peak = Math.max(peak, Math.abs(d[i])); }
  const k = peak > 0 ? 0.89 / peak : 1;
  const n = buf.length, out = new DataView(new ArrayBuffer(44 + n * 4));
  const W = (o, str) => { for (let i = 0; i < str.length; i++) out.setUint8(o + i, str.charCodeAt(i)); };
  W(0, 'RIFF'); out.setUint32(4, 36 + n * 4, true); W(8, 'WAVE'); W(12, 'fmt '); out.setUint32(16, 16, true); out.setUint16(20, 1, true); out.setUint16(22, 2, true);
  out.setUint32(24, SFX_SR, true); out.setUint32(28, SFX_SR * 4, true); out.setUint16(32, 4, true); out.setUint16(34, 16, true); W(36, 'data'); out.setUint32(40, n * 4, true);
  const L = buf.getChannelData(0), R = buf.getChannelData(1);
  for (let i = 0, p = 44; i < n; i++, p += 4) { out.setInt16(p, Math.max(-1, Math.min(1, L[i] * k)) * 32767, true); out.setInt16(p + 2, Math.max(-1, Math.min(1, R[i] * k)) * 32767, true); }
  const blob = new Blob([out.buffer], { type: 'audio/wav' });
  const r = { blob, url: URL.createObjectURL(blob) };
  sfxCache.set(s.id, r);
  return r;
}
const sfxSaved = new Map();
async function sfxFile(s) {
  if (sfxSaved.has(s.id)) return sfxSaved.get(s.id);
  const job = (async () => {
    const { blob } = await sfxRender(s);
    const name = 'SFX - ' + s.name.replace(/[\\/:*?"<>|()]+/g, '') + '.wav';
    if (!api || !api.saveMediaFile) return URL.createObjectURL(blob);
    return api.saveMediaFile({ folder: 'sound effects', name, data: await blob.arrayBuffer() });
  })();
  sfxSaved.set(s.id, job);
  try { return await job; } catch (e) { sfxSaved.delete(s.id); throw e; }
}
