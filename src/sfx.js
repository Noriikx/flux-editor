async function sfxImport(t) {
  // already in this project? use it again
  const have = P.media.find((m) => m.sfx === t.sfx && !m.missing);
  if (have) return have;
  const path = await sfxFile(sfxById(t.sfx));
  const [m] = await importFiles([{ path, name: t.title + '.wav', kind: 'audio', duration: t.length, tag: 'sfx' }]);
  if (m) m.sfx = t.sfx;
  return m;
}
// an audio track that's free at that moment, so a sound effect lands exactly at the playhead
function sfxTrackAt(at, len) {
  const free = (tr) => !tr.locked && !P.clips.some((o) => o.trackId === tr.id && o.start < at + len - 1e-4 && endOf(o) > at + 1e-4);
  const auds = P.tracks.filter((t) => t.type === 'audio');
  const named = auds.find((t) => /effect|sfx/i.test(t.name || '') && free(t));
  if (named) return named;
  const any = auds.slice().reverse().find(free);
  if (any) return any;
  const tr = { id: 'a' + uid().slice(0, 4), type: 'audio', name: 'Sound effects', auto: false, hidden: false, muted: false };
  P.tracks.push(tr);
  return tr;
}
