# Copies the shared logic from the desktop app into the phone version (website/lite/shared.js),
# so Viral Shorts scoring, the templates and template previews stay exactly the same on both.
import re, os
src = open('src/shorts.js').read().split('\n')
v7 = open('src/v7.js').read()
v71 = open('src/v71.js').read()
def block(text, start, end_marker):
    i = text.index(start); j = text.index(end_marker, i); return text[i:j]
out = ['// AUTO-GENERATED by tools/build-lite.py from the desktop app - do not edit here.', "'use strict';"]
out.append(next(l for l in src if l.startswith('const SH_RANGES')))
a = next(i for i, l in enumerate(src) if l.startswith('const SH_WORDS'))
b = next(i for i, l in enumerate(src) if l.startswith('/* ---------------- getting the words'))
out.append('\n'.join(src[a:b]))
out.append(block(v7, 'const TEMPLATES = [', '\n];') + '\n];')
out.append(block(v71, 'const BADGE_INFO = {', 'function badgesHtml'))
out.append(block(v71, 'const STATS_KEY', '// count things as they happen'))
out.append(block(v71, 'const ACH = [', 'let socialCounts'))
out.append(block(v71, 'const niceName =', 'const tplAnims'))
open('website/lite/shared.js', 'w').write('\n'.join(out) + '\n')
print('shared.js', os.path.getsize('website/lite/shared.js'), 'bytes')
